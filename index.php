					<h2>Histoire de Club-Internet (1995-2009)</h2>
					<img src="https://club-inter.net/picts/p.meilleur.gif" alt="A propos" title="Logo Le Meilleur du Net du 23 Décembre 1996 !" class="bloc-image">
				</div>
				<br>
				<div>
					<h3>1995-1998 : Les pionniers de l'Internet Français</h3>
					<p>
						<a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> fut créé le <strong>11 octobre 1995</strong> par <strong>Fabrice SERGENT</strong> et son équipe (Julien MITELBERG, Yann MAUCHAMP, Olivier MARTINERIE, Daniel GROSSMANN, Thuc Co DUCHEMIN, Michel BERA) au sein du groupe <em><a href="https://www.lagardere.com" title="Groupe Lagardère" target="_blank">Lagardère SCA</a></em> avec le soutien d'Arnaud LAGARDERE et Philippe CAMUS.
					</p>
					<p>
						Premier FAI Français grand public <em>avant</em> AOL et Wanadoo, <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> lança en novembre 1995 sa première offre RTC révolutionnaire à 77 francs par mois (hors communications) - le meilleur tarif du marché pour un service "ouvert".
					</p>
					<p>
						En septembre 1998, <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> adopte son fameux slogan <strong>"<em>Le Club le plus ouvert de la planète</em>"</strong> et lance sa première campagne publicitaire signée Publicis Technology, "<a href="https://youtu.be/KsX0XZ4gYBI" title="Autodafé Club-Internet - 1998" target="_blank">L'Autodafé</a>", qui fait exploser les abonnements de 300 à 2000 par jour !
					</p>
					<br>
					<h3>1999-2007 : L'âge d'or et les innovations</h3>
					<p>
						En janvier 1999, <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> devient le <strong>deuxième FAI Français</strong> après Wanadoo. Pionnier de l'ADSL, il propose dès novembre 1999 l'une des premières offres ADSL à 512 kbit/s en France.
					</p>
					<p>
						Face à la concurrence du "gratuit", <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> invente le <strong>premier forfait Internet incluant les communications téléphoniques</strong> - concept révolutionnaire pour l'époque ! Le même mois, il introduit la technologie du micropaiement en France.
					</p>
					<p>
						En février 2000, Deutsche Telekom rachète <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> (320 000 abonnés à l'époque). En mars 2000, nouvelle saga publicitaire de <strong>Luc BESSON</strong> pour 8 millions de francs - les pubs mythiques que l'on n'oublie pas !
					</p>
					<br>
					<h3>2007-2009 : La fin d'une époque</h3>
					<p>
						Le 2 juillet 2007, <strong>Neuf Cegetel</strong> rachète <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> pour 465 millions d'euros. L'objectif : faire migrer 90% des 600 000 abonnés vers la marque Neuf.
					</p>
					<p>
						Le 2 janvier 2008, le site <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> redirige vers "Neuf Club Internet avec AOL". Le 10 juin 2009, la messagerie @club-internet.fr migre définitivement vers SFR, marquant la <strong>fin officielle de Club-Internet</strong> après 14 ans d'innovation et de service.
					</p>
					<br>
					<h3>Depuis 2009 : La mémoire perpétuée</h3>
					<p>
						L'<strong><a href="https://club-inter.net" title="Club-Replugged">Association Club-Replugged</a></strong>, créée en 2009 par les anciens salariés, perpétue aujourd'hui la mémoire de cette aventure humaine et technologique exceptionnelle. Son président cofondateur, <strong><a href="https://mathieu.charreyre.net" title="Mathieu CHARREYRE">Mathieu CHARREYRE</a></strong>, fut l'un des tout premiers salariés de <a href="https://fr.wikipedia.org/wiki/Club_Internet" title="Fiche Wikipédia de Club-Internet" target="_blank"><em>Club-Internet</em></a> (20ème employé recruté en 1995) et resta dans l'aventure jusqu'au rachat par T-Online en 2000.
					</p>
					<p>
						Plus qu'une simple nostalgie, c'est la préservation d'un pan de l'histoire de l'Internet Français par ceux qui l'ont vécu de l'intérieur.
					</p>
					<br>
					<p class="center-text">
						<em><strong>"Le Club le plus ouvert de la planète"</strong> - Un slogan, une époque, une légende !</em>
					</p>
